/**
 * AI 输出的统一格式契约。
 *
 * 背景（2026-09-18 用户反馈）：「AI 的回答是直接把所有复制回来」——
 * 因为渲染端是 `whitespace-pre-wrap` 的纯文本，而提示词又要求模型输出
 * `**加粗**` 与 Markdown 表格，于是 `**`、`|` 全都原样显示出来。
 *
 * 修法分两半，必须成对：
 *  1. 渲染端改用 `AiMarkdown`（src/components/ai-markdown.tsx），真的把 Markdown 渲染出来；
 *  2. 提示词端统一约定「输出合同」——只允许使用渲染端明确支持的那几种结构，
 *     并且**禁止自己造层级符号**（`【】`、`===`、`---`、`▪`、全角竖线表格等）。
 *     没有这一半，模型会继续用自由格式，渲染端再怎么修也是「渲染别人的随机格式」。
 *
 * 于是「AI 回答长什么样」这件事，从 8 个面板各自为政，收敛成一处定义。
 */

/** 输出级（与 lib/planner/ai.ts 同一条思路：提示词里写死的格式，必须与解析/渲染逻辑对齐） */
export const OUTPUT_FORMAT_CONTRACT = `## 输出格式（必须严格遵守）
- 用 Markdown 组织内容；**只使用**下列结构：# / ## / ### 标题、无序列表（-）、有序列表（1.）、
  **加粗**、表格（标准的 | 分隔，第二行为 |---| 分隔线）。
- **不要**使用其它任何层级或装饰符号：不要写【】、不要写 === 或 --- 分隔线、不要写
  ▪ ● ◆ 之类的项目符号、不要用全角竖线（｜）画表格、不要用连续空格排版、不要输出 HTML 标签。
- 表格每一行的列数必须与表头一致；单元格内容保持简短，不要在单元格里换行。
- 层级只靠标题与列表嵌套体现；除标题外不要用 # 号做点缀。
- 数字与单位之间不加空格；数值保留原样，不要自行换算或四舍五入。`

/**
 * 标题层级（防止面板把 `#` 当 h1 渲染成巨字把布局撑爆）。
 *
 * 面板里的这块内容本身已经是卡片内的一个区块，`#` 只应表达「本文档最高层」。
 * 提示词里要求从 `##` 起算，渲染端再兜一道（见 AiMarkdown 的 clampHeading）。
 */
export const HEADING_LEVEL_RULE = '标题从 `##` 开始往下用（`##` / `###` / `####`），不要使用一级标题 `#`。'
